DEFAULT_LANGUAGE = "en"
_LANGUAGE = DEFAULT_LANGUAGE


def set_language(language: str) -> str:
    """Set and return the active dashboard language."""

    global _LANGUAGE
    if language not in TRANSLATIONS:
        raise ValueError(f"Unsupported language: {language}")
    _LANGUAGE = language
    st.session_state["dashboard_language"] = language
    return language


def current_language() -> str:
    """Return the active dashboard language."""

    return str(st.session_state.get("dashboard_language", _LANGUAGE))


def t(key: str, **kwargs: object) -> str:
    """Translate a dashboard key, falling back to English and then the key."""

    language = current_language()
    text = TRANSLATIONS.get(language, {}).get(key, TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key))
    return text.format(**kwargs) if kwargs else text
